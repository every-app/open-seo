// Canonical schema barrel. Repositories import their tables from here and the
// provider-aware `db` from "@/db", so each repository is written ONCE for both
// backends.
//
// The TYPE identity is the SQLite definitions; the runtime VALUES are whichever
// provider is active. `schema-parity.test.ts` asserts the two dialect schemas
// are structurally interchangeable (same tables/columns/nullability/PKs/unique
// indexes), which is what makes the single cast below sound. The Postgres
// schema is the one structural artifact NOT regenerated by `db:generate`, so the
// parity test is its drift guard.
type AppSchema = typeof sqliteApp &
  typeof sqliteProjectContext &
  typeof sqliteReports &
  typeof sqliteReportTemplates &
  typeof sqliteAudit &
  typeof sqliteSam &
  typeof sqliteAuth &
  typeof sqliteBilling &
  typeof sqliteBing &
  typeof sqliteGa4 &
  typeof sqliteGsc &
  typeof sqliteTelemetry &
  typeof sqliteAiVisibility;

const runtimeSchema =
  getDatabaseProvider() === "postgres"
    ? {
        ...pgApp,
        ...pgProjectContext,
        ...pgReports,
        ...pgReportTemplates,
        ...pgAudit,
        ...pgSam,
        ...pgAuth,
        ...pgBilling,
        ...pgBing,
        ...pgGa4,
        ...pgGsc,
        ...pgTelemetry,
        ...pgAiVisibility,
      }
    : {
        ...sqliteApp,
        ...sqliteProjectContext,
        ...sqliteReports,
        ...sqliteReportTemplates,
        ...sqliteAudit,
        ...sqliteSam,
        ...sqliteAuth,
        ...sqliteBilling,
        ...sqliteBing,
        ...sqliteGa4,
        ...sqliteGsc,
        ...sqliteTelemetry,
        ...sqliteAiVisibility,
      };

// oxlint-disable-next-line typescript/no-unsafe-type-assertion -- guarded by schema-parity.test.ts
const schema = runtimeSchema as unknown as AppSchema;

